import boardsIndex from '../../circuits/boards-index.json' with { type: 'json' };
import type { Part, PinMode } from './schematic-types';

export interface BoardPin {
  id: string; name: string; kind: 'gpio' | 'input_only' | 'power' | 'ground' | 'special'; gpio: number | null;
  functions: string[]; voltage: number | null; current_max: number | null; fixed_pull_up: number | null;
  note: string; modes: PinMode[];
}
export interface Board {
  id: string; name: string; description: string; header: string; columns: 1 | 2; trust: 'draft' | 'verified';
  documentation: string | null; logic_voltage: number; pins: BoardPin[];
  ratings: Record<string, { value: number; unit: string }>;
}

// Generated by `python -m backend.parts_cli index`; CI checks it matches the validated board files.
export const BOARDS = boardsIndex as unknown as Board[];

export const MODE_NAMES: Record<PinMode, string> = {
  output_high: 'Output high', output_low: 'Output low', pulse: 'Output pulse / PWM', input: 'Input (no pull)',
  input_pull_up: 'Input, pull-up', input_pull_down: 'Input, pull-down', supply: 'Power supply',
};

export function boardOf(id: string | undefined): Board | undefined {
  return BOARDS.find(board => board.id === id);
}

export function boardPinOf(part: Part): { board: Board; pin: BoardPin } | undefined {
  const board = boardOf(part.board_pin?.board);
  const pin = board?.pins.find(candidate => candidate.id === part.board_pin?.pin);
  return board && pin ? { board, pin } : undefined;
}

/** Pins a circuit can use: everything except ground (use the Ground symbol) and special pins. */
export function placeablePins(board: Board): BoardPin[] {
  return board.pins.filter(pin => pin.modes.length > 0);
}

export function pinLabel(pin: BoardPin): string {
  const position = /^\d+$/.test(pin.id) ? 'pin ' + pin.id : pin.id;
  return position === pin.name ? pin.name : position + ' · ' + pin.name;
}

/** "Raspberry Pi 4 · pin 11 · GPIO17 · Output high", or a fallback for an unknown pin. */
export function boardPinDescription(part: Part): string {
  const found = boardPinOf(part);
  if (!found || !part.board_pin) return 'unknown board pin';
  return found.board.name.replace(' Model B', '') + ' · ' + pinLabel(found.pin) + ' · ' + MODE_NAMES[part.board_pin.mode];
}
